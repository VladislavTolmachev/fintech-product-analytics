-- Fintech Product Analytics
-- PostgreSQL schema. Uses synthetic data only.

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signup_at TIMESTAMP NOT NULL,
    acquisition_channel VARCHAR(50) NOT NULL,
    country_code CHAR(2) NOT NULL DEFAULT 'MX'
);

CREATE TABLE card_applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    submitted_at TIMESTAMP NOT NULL,
    decision_at TIMESTAMP,
    application_status VARCHAR(20) NOT NULL
        CHECK (application_status IN ('pending', 'approved', 'rejected')),
    CHECK (decision_at IS NULL OR decision_at >= submitted_at),
    CHECK (
        (application_status = 'pending' AND decision_at IS NULL)
        OR
        (application_status IN ('approved', 'rejected') AND decision_at IS NOT NULL)
    )
);

CREATE TABLE cards (
    card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE
        REFERENCES card_applications(application_id),
    issued_at TIMESTAMP NOT NULL,
    activated_at TIMESTAMP,
    card_status VARCHAR(20) NOT NULL
        CHECK (card_status IN ('issued', 'active', 'blocked', 'closed')),
    CHECK (activated_at IS NULL OR activated_at >= issued_at),
    CHECK (
        (card_status = 'issued' AND activated_at IS NULL)
        OR
        (card_status IN ('active', 'blocked', 'closed') AND activated_at IS NOT NULL)
    )
);

CREATE TABLE transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL REFERENCES cards(card_id),
    transaction_at TIMESTAMP NOT NULL,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    transaction_type VARCHAR(20) NOT NULL
        CHECK (transaction_type IN ('purchase', 'refund', 'cash_withdrawal')),
    transaction_status VARCHAR(20) NOT NULL
        CHECK (transaction_status IN ('completed', 'declined', 'reversed'))
);

CREATE TABLE user_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    event_time TIMESTAMP NOT NULL,
    event_name VARCHAR(50) NOT NULL,
    session_id VARCHAR(100)
);

CREATE INDEX idx_applications_user ON card_applications(user_id);
CREATE INDEX idx_applications_submitted ON card_applications(submitted_at);
CREATE INDEX idx_cards_application ON cards(application_id);
CREATE INDEX idx_transactions_card_time ON transactions(card_id, transaction_at);
CREATE INDEX idx_events_user_time ON user_events(user_id, event_time);